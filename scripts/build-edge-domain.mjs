#!/usr/bin/env node
/**
 * Bundles the pure domain logic (src/domain/server.ts) into a single ES module
 * that Supabase Edge Functions (Deno) can import, so the server uses exactly
 * the same schedule/streak rules as the app.
 *
 *   node scripts/build-edge-domain.mjs           # write the bundle
 *   node scripts/build-edge-domain.mjs --check   # fail if the bundle is stale
 */
import { build } from 'esbuild';
import ts from 'typescript';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const domainDir = join(root, 'src/domain');
const outFile = join(root, 'supabase/functions/_shared/domain.js');
const typesFile = join(root, 'supabase/functions/_shared/domain.d.ts');
// Modules whose declarations make up the public surface (dependency order).
const DECLARATION_MODULES = ['types', 'dates', 'schedule', 'stats', 'nudges'];

const sources = readdirSync(domainDir)
  .filter((f) => f.endsWith('.ts'))
  .sort();
const hash = createHash('sha256');
for (const f of sources) hash.update(f).update(readFileSync(join(domainDir, f)));
const digest = hash.digest('hex').slice(0, 16);
const header = `// @ts-self-types="./domain.d.ts"\n// GENERATED by scripts/build-edge-domain.mjs from src/domain — do not edit.\n// source-hash: ${digest}\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (!current.includes(`source-hash: ${digest}`)) {
    console.error('supabase/functions/_shared/domain.js is out of date. Run: npm run build:edge');
    process.exit(1);
  }
  process.exit(0);
}

const result = await build({
  entryPoints: [join(domainDir, 'server.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  write: false,
  legalComments: 'none',
});
writeFileSync(outFile, header + result.outputFiles[0].text);

// Single-file declarations: emit per-module .d.ts and merge them, dropping the
// relative imports between domain modules (everything lives in one module now).
const declarations = {};
const program = ts.createProgram(
  DECLARATION_MODULES.map((m) => join(domainDir, `${m}.ts`)),
  { declaration: true, emitDeclarationOnly: true, strict: true, target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, skipLibCheck: true },
);
program.emit(undefined, (name, text) => {
  declarations[name.replace(/^.*\//, '').replace(/\.d\.ts$/, '')] = text;
}, undefined, true);
const merged = DECLARATION_MODULES.map((m) => {
  if (!declarations[m]) throw new Error(`No declarations emitted for ${m}`);
  return `// --- ${m}\n` + declarations[m]
    .split('\n')
    .filter((line) => !/^import .* from '\.\/[a-z-]+';$/.test(line) && line.trim() !== 'export {};')
    .join('\n');
}).join('\n');
writeFileSync(typesFile, `// GENERATED by scripts/build-edge-domain.mjs — do not edit.\n// source-hash: ${digest}\n` + merged);
console.log(`Wrote ${outFile.replace(root + '/', '')} + domain.d.ts (${digest})`);
